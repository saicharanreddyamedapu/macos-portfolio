const { chromium } = require('playwright')
const fs = require('fs')
const path = require('path')
const crypto = require('crypto')
const portfolio = require('../src/data/portfolioData.json')
const base = process.env.PORTFOLIO_TEST_URL || 'http://localhost:5173'

async function main() {
  const browser = await chromium.launch({ headless: true, ...(process.env.PLAYWRIGHT_BROWSER_PATH ? { executablePath: process.env.PLAYWRIGHT_BROWSER_PATH } : {}) })
  const out = path.join(process.cwd(), 'qa', 'startup-regression')
  fs.mkdirSync(out, { recursive: true })
  const errors = []
  const context = await browser.newContext({ viewport: { width: 1440, height: 900 } })
  const page = await context.newPage()
  page.on('pageerror', err => errors.push(err.message))
  page.on('console', msg => { if (msg.type() === 'error') errors.push(msg.text()) })
  page.on('response', response => { if (response.status() >= 400) errors.push(response.status() + ' ' + response.url()) })
  await page.goto(base, { waitUntil: 'networkidle' })
  await page.waitForFunction(() => [...document.querySelectorAll('.desktop-icons img, .dock img')].every(img => img.complete && img.naturalWidth > 0))
  const fixedDock = await page.locator('.dock-item').evaluateAll(items => items.map(item => item.getAttribute('aria-label')))
  if (fixedDock.join('|') !== ['Open Finder', 'Open Safari', 'Open Gallery', 'Open Skills Terminal', 'Open Contact', 'Open Appearance', 'Open Trash'].join('|')) throw Error('Dock application order incorrect')
  if (await page.locator('.dock-item img[src="/icons/folder.svg"]').count()) throw Error('Duplicate folders remain in the dock')
  if (!(await page.locator('.apple-mark').isVisible())) throw Error('Menu bar Apple mark missing')
  const safariDock = page.locator('.dock-safari')
  await safariDock.hover()
  await page.waitForTimeout(160)
  if (await safariDock.evaluate(el => Number(getComputedStyle(el).getPropertyValue('--dock-scale'))) !== 1.33) throw Error('Dock magnification failed')
  if (!(await safariDock.locator('.dock-tooltip').isVisible())) throw Error('Dock tooltip missing')
  await page.mouse.move(1000, 50)
  const clockText = await page.locator('.topbar time').innerText()
  const dateParts = await page.evaluate(() => new Intl.DateTimeFormat(undefined, { weekday: 'short', month: 'short', day: 'numeric' }).format(new Date()))
  if (!clockText.includes(dateParts)) throw Error('Menu bar date is missing')
  await page.screenshot({ path: path.join(out, 'desktop.png') })
  if (!(await page.getByRole('heading', { name: /Sai Charan/ }).count())) throw Error('Desktop hero missing')
  await page.getByRole('navigation', { name: 'Main' }).getByRole('button', { name: 'Projects' }).click()
  const projects = page.getByRole('dialog', { name: 'Projects' })
  await projects.waitFor()
  if (await projects.locator('.project-tile').count() !== 6) throw Error('Expected six projects')
  await projects.getByRole('button', { name: 'AI / Machine Learning', exact: true }).click()
  if (await projects.locator('.project-tile').count() !== 3) throw Error('AI project filter failed')
  await projects.locator('.project-tile').first().click()
  if (!(await projects.getByText('Repository').isVisible())) throw Error('Project detail missing repository')
  await projects.getByRole('button', { name: 'Minimize Projects' }).click()
  if (await projects.isVisible()) throw Error('Minimize failed')
  await page.getByRole('button', { name: 'Restore Projects' }).click()
  await projects.waitFor()
  if (!(await projects.getByText('Repository').isVisible())) throw Error('Minimize lost project detail')
  if (await page.locator('.dock-projects').count()) throw Error('Temporary minimized project remained in the dock')
  await projects.getByRole('button', { name: 'Maximize Projects' }).click()
  if (!(await projects.evaluate(el => el.classList.contains('maximized')))) throw Error('Maximize failed')
  await projects.getByRole('button', { name: 'Restore Projects' }).click()
  await projects.getByRole('button', { name: 'Close Projects' }).click()
  await page.getByRole('navigation', { name: 'Main' }).getByRole('button', { name: 'Resume' }).click()
  const resume = page.getByRole('dialog', { name: 'Resume' })
  await resume.waitFor()
  for (const [i, filename] of ['AI&Development_resume.pdf', 'AI_Resume.pdf', 'Development_resume.pdf'].entries()) {
    await resume.locator('.resume-item').nth(i).click()
    const src = await resume.locator('iframe').getAttribute('src')
    if (!src.includes(filename)) throw Error('Resume selection failed: ' + filename)
    const response = await page.request.get(base + src)
    if (response.status() !== 200 || !response.headers()['content-type']?.includes('pdf')) throw Error('PDF unavailable: ' + filename)
    if (i === 0) { await page.waitForTimeout(500); await page.screenshot({ path: path.join(out, 'resume-desktop.png') }) }
    const [download] = await Promise.all([page.waitForEvent('download'), resume.getByRole('link', { name: 'Download' }).click()])
    if (download.suggestedFilename() !== filename) throw Error('Incorrect downloaded PDF name: ' + filename)
    const hash = data => crypto.createHash('sha256').update(data).digest('hex')
    if (hash(fs.readFileSync(await download.path())) !== hash(fs.readFileSync(path.join('public', 'resumes', filename)))) throw Error('Downloaded PDF differs: ' + filename)
  }
  await resume.getByRole('button', { name: 'Close Resume' }).click()
  await page.getByRole('button', { name: 'Open Appearance' }).click().catch(async () => page.locator('.dock-settings').click())
  const settings = page.getByRole('dialog', { name: 'Appearance' })
  await settings.getByRole('radio', { name: /Dark/ }).check()
  if (await page.locator('html').getAttribute('data-theme') !== 'dark') throw Error('Dark theme failed')
  await page.waitForFunction(() => getComputedStyle(document.querySelector('.wallpaper'), '::after').opacity === '1')
  await page.screenshot({ path: path.join(out, 'desktop-dark.png') })
  await settings.getByRole('radio', { name: /^Light/ }).check()
  await page.waitForFunction(() => getComputedStyle(document.querySelector('.wallpaper'), '::after').opacity === '0')
  if (await page.locator('#portfolio-boot').count()) throw Error('Startup returned during theme switching')
  await page.screenshot({ path: path.join(out, 'desktop-light.png') })
  await settings.getByRole('radio', { name: /Dark/ }).check()
  await settings.getByRole('button', { name: 'Close Appearance' }).click()
  await page.getByRole('button', { name: 'Open Trash' }).click()
  const trash = page.getByRole('dialog', { name: 'Trash' })
  if (!(await trash.getByText('Trash is Empty').isVisible())) throw Error('Empty Trash missing')
  if (await page.locator('.dock-trash i').count() !== 1) throw Error('Trash active indicator missing')
  await trash.getByRole('button', { name: 'Minimize Trash' }).click()
  await page.getByRole('button', { name: 'Restore Trash' }).click()
  if (!(await trash.getByText('Trash is Empty').isVisible())) throw Error('Trash restore failed')
  await trash.getByRole('button', { name: 'Maximize Trash' }).click()
  await trash.getByRole('button', { name: 'Restore Trash' }).click()
  await trash.getByRole('button', { name: 'Close Trash' }).click()
  await page.getByRole('button', { name: 'Open Safari' }).click()
  const safari = page.getByRole('dialog', { name: 'Safari' })
  if (await safari.locator('article').count() !== 3) throw Error('Safari profile articles missing')
  for (const [name, url] of Object.entries({ LinkedIn: portfolio.profiles.linkedin, GitHub: portfolio.profiles.github, LeetCode: portfolio.profiles.leetcode })) {
    const link = safari.getByRole('link', { name: 'Visit ' + name })
    if (await link.getAttribute('href') !== url || await link.getAttribute('target') !== '_blank') throw Error('Incorrect ' + name + ' profile link')
  }
  await page.waitForTimeout(350)
  await page.screenshot({ path: path.join(out, 'safari.png') })
  await safari.getByRole('button', { name: 'Minimize Safari' }).click()
  await page.getByRole('button', { name: 'Restore Safari' }).click()
  await safari.getByRole('button', { name: 'Close Safari' }).click()
  await page.getByRole('button', { name: 'Open Gallery' }).click()
  const gallery = page.getByRole('dialog', { name: 'Gallery' })
  if (await gallery.locator('.gallery-tile').count() !== 2) throw Error('Gallery photos missing')
  await gallery.locator('.gallery-tile img').evaluateAll(imgs => Promise.all(imgs.map(img => img.decode())))
  await page.waitForTimeout(350)
  await page.screenshot({ path: path.join(out, 'gallery.png') })
  await gallery.getByRole('button', { name: 'View photo: Bennett University' }).click()
  if (!(await gallery.getByRole('img', { name: /A-Block at Bennett University/ }).isVisible())) throw Error('Campus photo detail missing')
  if (!(await gallery.getByRole('link', { name: 'Image source' }).isVisible())) throw Error('Campus photo attribution missing')
  await gallery.getByRole('button', { name: 'All photos' }).click()
  await gallery.getByRole('button', { name: 'View photo: Sai Charan Reddy' }).click()
  if (!(await gallery.getByRole('img', { name: 'Portrait of Sai Charan Reddy' }).isVisible())) throw Error('Portrait detail missing')
  await gallery.getByRole('button', { name: 'Close Gallery' }).click()
  await page.locator('.dock-finder').click()
  const finder = page.getByRole('dialog', { name: 'Finder' })
  await finder.waitFor()
  await finder.locator('.finder-items button').filter({ hasText: 'Projects' }).click()
  await finder.locator('.finder-items button').filter({ hasText: 'AI / Machine Learning' }).click()
  await finder.locator('.finder-items button').filter({ hasText: 'SkillLens' }).click()
  const skillLens = page.getByRole('dialog', { name: 'SkillLens' })
  if (!(await skillLens.isVisible())) throw Error('Finder project navigation failed')
  if (Number(await skillLens.evaluate(el => getComputedStyle(el).zIndex)) <= Number(await finder.evaluate(el => getComputedStyle(el).zIndex))) throw Error('New window did not gain focus')
  await finder.locator('.window-header').click({ position: { x: 3, y: 20 } })
  if (Number(await finder.evaluate(el => getComputedStyle(el).zIndex)) <= Number(await skillLens.evaluate(el => getComputedStyle(el).zIndex))) throw Error('Window focus did not change')
  await finder.getByRole('button', { name: 'Minimize Finder' }).click()
  await page.locator('.dock-finder').click()
  await finder.locator('.finder-items button').filter({ hasText: 'SkillLens' }).click()
  await page.getByRole('dialog', { name: 'SkillLens' }).getByRole('button', { name: 'Close SkillLens' }).click()
  const beforeDrag = await finder.boundingBox()
  const header = await finder.locator('.window-header').boundingBox()
  await page.mouse.move(header.x + header.width / 2, header.y + 22)
  await page.mouse.down(); await page.mouse.move(header.x + header.width / 2 + 35, header.y + 35, { steps: 6 }); await page.mouse.up()
  const afterDrag = await finder.boundingBox()
  if (Math.abs(afterDrag.x - beforeDrag.x) < 15) throw Error('Window dragging failed')
  const beforeResize = await finder.boundingBox()
  const handle = await finder.locator('.resize-handle').boundingBox()
  await page.mouse.move(handle.x + 10, handle.y + 10)
  await page.mouse.down(); await page.mouse.move(handle.x + 35, handle.y + 30, { steps: 5 }); await page.mouse.up()
  const afterResize = await finder.boundingBox()
  if (afterResize.width < beforeResize.width + 10) throw Error('Window resizing failed')
  await finder.getByRole('button', { name: 'Close Finder' }).click()
  await page.locator('.dock-skills').click()
  const terminal = page.getByRole('dialog', { name: 'Skills Terminal' })
  await terminal.locator('#command').fill('whoami')
  await terminal.locator('#command').press('Enter')
  if (!(await terminal.getByText('Sai Charan Reddy', { exact: true }).isVisible())) throw Error('Terminal command failed')
  const terminalCommand = async (command, expected) => {
    await terminal.locator('#command').fill(command)
    await terminal.locator('#command').press('Enter')
    if (expected && !(await terminal.getByText(expected, { exact: false }).last().isVisible())) throw Error('Terminal command failed: ' + command)
  }
  await terminalCommand('help', 'skills [group]')
  await terminalCommand('about', 'AI/ML & Full-Stack Developer')
  await terminalCommand('skills languages', 'Languages: Python')
  await terminalCommand('projects', 'SkillLens')
  await terminalCommand('education', 'Bennett University')
  await terminalCommand('certifications', 'Data Structures')
  await terminalCommand('contact', portfolio.personal.email)
  await terminalCommand('not-a-command', 'Command not found')
  await terminalCommand('resume ai-ml', 'Opened AI / ML Resume')
  const terminalResume = page.getByRole('dialog', { name: 'Resume' })
  if (!(await terminalResume.getByText('AI / ML Resume', { exact: true }).first().isVisible())) throw Error('Terminal did not open the selected resume')
  await terminalResume.getByRole('button', { name: 'Close Resume' }).click()
  await terminalCommand('clear')
  if (await terminal.locator('#command').inputValue() !== '' || await terminal.locator('.terminal-entry').count() !== 0) throw Error('Terminal clear failed')
  await terminal.locator('#command').press('ArrowUp')
  if (await terminal.locator('#command').inputValue() !== 'clear') throw Error('Terminal history failed')
  await terminal.getByRole('button', { name: 'Close Skills Terminal' }).click()
  for (const [id, title, text] of [['about', 'About Me', 'Sai Charan Reddy'], ['contact', 'Contact', 'LinkedIn']]) {
    if (id === 'about') await page.locator('.desktop-icons button[title="Open About Me"]').click()
    else await page.locator('.dock-' + id).click()
    const win = page.getByRole('dialog', { name: title })
    if (!(await win.getByText(text, { exact: true }).first().isVisible())) throw Error(title + ' content missing')
    await win.getByRole('button', { name: 'Close ' + title }).click()
  }
  await page.locator('.dock-finder').click()
  await page.getByRole('dialog', { name: 'Finder' }).locator('.finder-sidebar').getByRole('button', { name: 'Certificates' }).click()
  const certificates = page.getByRole('dialog', { name: 'Certificates' })
  if (!(await certificates.getByText('Data Structures', { exact: true }).isVisible())) throw Error('Certificates content missing')
  await certificates.getByRole('button', { name: 'Close Certificates' }).click()
  await page.getByRole('dialog', { name: 'Finder' }).locator('.finder-sidebar').getByRole('button', { name: 'Education' }).click()
  const education = page.getByRole('dialog', { name: 'Education' })
  if (!(await education.getByText('Bennett University', { exact: true }).isVisible())) throw Error('Education content missing')
  await education.getByRole('button', { name: 'Close Education' }).click()
  await page.getByRole('dialog', { name: 'Finder' }).getByRole('button', { name: 'Close Finder' }).click()
  await page.reload({ waitUntil: 'networkidle' })
  if (await page.locator('html').getAttribute('data-theme') !== 'dark') throw Error('Theme persistence failed')
  await context.close()

  const clockContext = await browser.newContext({ viewport: { width: 1440, height: 900 } })
  const clockPage = await clockContext.newPage()
  await clockPage.clock.install({ time: new Date(2026, 9, 29, 23, 59, 58) })
  await clockPage.goto(base, { waitUntil: 'domcontentloaded' })
  const beforeMidnight = await clockPage.locator('.topbar time').innerText()
  await clockPage.clock.fastForward('00:00:03')
  await clockPage.waitForFunction(previous => {
    const current = document.querySelector('.topbar time')?.innerText
    return current && current !== previous && current.includes('30')
  }, beforeMidnight)
  const afterMidnight = await clockPage.locator('.topbar time').innerText()
  if (beforeMidnight === afterMidnight || !afterMidnight.includes('30')) throw Error('Clock did not update across midnight')
  await clockContext.close()

  const systemContext = await browser.newContext({ viewport: { width: 1440, height: 900 }, colorScheme: 'dark', reducedMotion: 'reduce' })
  const systemPage = await systemContext.newPage()
  await systemPage.goto(base, { waitUntil: 'networkidle' })
  if (await systemPage.locator('html').getAttribute('data-theme') !== 'system') throw Error('System theme default missing')
  if (await systemPage.evaluate(() => getComputedStyle(document.querySelector('.wallpaper'), '::after').opacity) !== '1') throw Error('System dark wallpaper missing')
  if (await systemPage.evaluate(() => getComputedStyle(document.querySelector('.wallpaper'), '::after').transitionDuration) !== '0s') throw Error('Reduced motion ignored')
  await systemPage.emulateMedia({ colorScheme: 'light', reducedMotion: 'reduce' })
  if (await systemPage.evaluate(() => getComputedStyle(document.querySelector('.wallpaper'), '::after').opacity) !== '0') throw Error('System light wallpaper missing')
  await systemContext.close()

  for (const [width, height, name] of [[768, 1024, 'tablet'], [1440, 720, 'short-desktop']]) {
    const ctx = await browser.newContext({ viewport: { width, height } })
    const p = await ctx.newPage()
    await p.goto(base, { waitUntil: 'networkidle' })
    if (!(await p.locator('.desktop-shell').isVisible())) throw Error(name + ' did not retain desktop shell')
    if (await p.evaluate(() => document.documentElement.scrollWidth > innerWidth)) throw Error(name + ' horizontal overflow')
    await p.screenshot({ path: path.join(out, name + '.png') })
    await ctx.close()
  }

  const mobileContext = await browser.newContext({ viewport: { width: 390, height: 844 }, isMobile: true, deviceScaleFactor: 1 })
  const phone = await mobileContext.newPage()
  phone.on('pageerror', err => errors.push(err.message))
  phone.on('console', msg => { if (msg.type() === 'error') errors.push(msg.text()) })
  await phone.goto(base, { waitUntil: 'networkidle' })
  await phone.waitForFunction(() => [...document.querySelectorAll('.mobile-icon-grid img')].every(img => img.complete && img.naturalWidth > 0))
  await phone.screenshot({ path: path.join(out, 'mobile.png') })
  const overflow = await phone.evaluate(() => document.documentElement.scrollWidth > innerWidth)
  if (overflow) throw Error('Mobile horizontal overflow')
  await phone.locator('.mobile-icon-grid button').first().click()
  if (!(await phone.locator('.mobile-sheet').isVisible())) throw Error('Mobile app did not open')
  if (await phone.locator('.project-tile').count() !== 6) throw Error('Mobile projects missing')
  await phone.getByRole('button', { name: /Done/ }).click()
  await phone.locator('.mobile-icon-grid button').nth(1).click()
  const mobileResume = phone.locator('.mobile-sheet')
  for (const id of ['ai-fullstack', 'ai-ml', 'software-development']) {
    await mobileResume.locator('#resume-choice').selectOption(id)
    await phone.waitForTimeout(1200)
    if (await mobileResume.getByText('Preview unavailable').count()) throw Error('Mobile PDF failed: ' + id + ' / ' + errors.join(' | '))
    await phone.waitForFunction(() => document.querySelector('.mobile-pdf-preview .sr-only')?.textContent.length > 100)
  }
  await mobileResume.getByRole('button', { name: 'Zoom in' }).click()
  if (!(await mobileResume.getByText('125%').isVisible())) throw Error('Mobile PDF zoom failed')
  await mobileResume.getByRole('button', { name: 'Zoom out' }).click()
  await phone.waitForTimeout(800)
  await phone.waitForTimeout(350)
  await phone.screenshot({ path: path.join(out, 'mobile-resume.png') })
  await phone.getByRole('button', { name: /Done/ }).click()
  await phone.getByRole('button', { name: 'Open Safari' }).click()
  if (await phone.locator('.mobile-sheet article').count() !== 3) throw Error('Mobile Safari profile articles missing')
  await phone.getByRole('button', { name: /Done/ }).click()
  await phone.getByRole('button', { name: 'Open Gallery' }).click()
  if (await phone.locator('.mobile-sheet .gallery-tile').count() !== 2) throw Error('Mobile gallery photos missing')
  await phone.locator('.mobile-sheet .gallery-tile img').evaluateAll(imgs => Promise.all(imgs.map(img => img.decode())))
  await phone.waitForTimeout(350)
  await phone.screenshot({ path: path.join(out, 'mobile-gallery.png') })
  await mobileContext.close()
  await browser.close()
  if (errors.length) throw Error('Browser errors: ' + errors.join(' | '))
  console.log('Browser checks passed: desktop windows, filtering, three PDFs, theme, mobile navigation and layout.')
}
main().catch(err => { console.error(err); process.exitCode = 1 })
