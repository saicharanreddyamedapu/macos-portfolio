const { chromium } = require('playwright')
const fs = require('fs')
const path = require('path')

const base = process.env.PORTFOLIO_TEST_URL || 'http://127.0.0.1:5173'
const entry = /\/(?:src\/main\.jsx|assets\/index-[^/]+\.js)(?:\?.*)?$/
const pause = ms => new Promise(resolve => setTimeout(resolve, ms))
const assert = (condition, message) => { if (!condition) throw Error(message) }

async function main() {
  const browser = await chromium.launch({ headless: true, ...(process.env.PLAYWRIGHT_BROWSER_PATH ? { executablePath: process.env.PLAYWRIGHT_BROWSER_PATH } : {}) })
  const out = path.join(process.cwd(), 'qa', 'startup-regression')
  fs.mkdirSync(out, { recursive: true })
  try {
    const desktopContext = await browser.newContext({ viewport: { width: 1440, height: 900 } })
    const desktop = await desktopContext.newPage()
    const errors = []
    desktop.on('pageerror', e => errors.push(e.message))
    await desktop.route(entry, async route => { await pause(1100); await route.continue() })
    await desktop.goto(base, { waitUntil: 'commit' })
    await desktop.locator('#portfolio-boot').waitFor({ state: 'visible' })
    assert(await desktop.locator('.boot-logo').isVisible(), 'Startup logo missing')
    assert(await desktop.getByRole('progressbar', { name: 'Loading portfolio' }).isVisible(), 'Startup progress bar missing')
    assert(await desktop.locator('#root').evaluate(el => el.hasAttribute('inert') && getComputedStyle(el).visibility === 'hidden'), 'Desktop was exposed before startup')
    await desktop.screenshot({ path: path.join(out, 'startup-desktop.png') })
    await desktop.waitForFunction(() => document.querySelector('.boot-fill')?.style.transform === 'scaleX(1)')
    await desktop.locator('#portfolio-boot').waitFor({ state: 'detached' })
    assert(await desktop.locator('#root').evaluate(el => !el.hasAttribute('inert') && !el.hasAttribute('aria-hidden')), 'Desktop remained blocked after startup')
    await desktop.getByRole('button', { name: 'Open Finder' }).click()
    assert(await desktop.getByRole('dialog', { name: 'Finder' }).isVisible(), 'Desktop is not interactive after startup')
    assert(await desktop.locator('#portfolio-boot').count() === 0, 'Startup returned during internal navigation')
    await desktop.reload({ waitUntil: 'commit' })
    await desktop.locator('#portfolio-boot').waitFor({ state: 'visible' })
    await desktop.locator('#portfolio-boot').waitFor({ state: 'detached' })
    assert(errors.length === 0, 'Unexpected startup errors: ' + errors.join(', '))
    await desktopContext.close()

    const cachedContext = await browser.newContext({ viewport: { width: 1440, height: 900 } })
    const cached = await cachedContext.newPage()
    const timings = []
    for (let i = 0; i < 2; i++) {
      const started = Date.now()
      if (i === 0) await cached.goto(base, { waitUntil: 'domcontentloaded' })
      else await cached.reload({ waitUntil: 'domcontentloaded' })
      await cached.locator('#portfolio-boot').waitFor({ state: 'detached', timeout: 5000 })
      timings.push(Date.now() - started)
    }
    assert(timings[1] < 3000, 'Cached startup took unexpectedly long: ' + timings[1] + 'ms')
    console.log('Local startup timings (initial / cached): ' + timings.join(' / ') + ' ms')
    await cachedContext.close()

    const wallpaperContext = await browser.newContext({ viewport: { width: 1440, height: 900 } })
    await wallpaperContext.addInitScript(() => localStorage.setItem('portfolio-theme', 'light'))
    const wallpaper = await wallpaperContext.newPage()
    await wallpaper.route('**/wallpapers/light.webp', async route => { await pause(1200); await route.continue() })
    await wallpaper.goto(base, { waitUntil: 'domcontentloaded' })
    await wallpaper.waitForTimeout(300)
    assert(await wallpaper.locator('#portfolio-boot').isVisible(), 'Startup finished before the selected wallpaper settled')
    await wallpaper.locator('#portfolio-boot').waitFor({ state: 'detached', timeout: 5000 })
    assert(await wallpaper.locator('html').getAttribute('data-theme') === 'light', 'Saved light theme was lost')
    await wallpaperContext.close()

    const missingContext = await browser.newContext({ viewport: { width: 1440, height: 900 } })
    await missingContext.addInitScript(() => localStorage.setItem('portfolio-theme', 'dark'))
    const missing = await missingContext.newPage()
    await missing.route('**/wallpapers/dark.png', route => route.abort())
    await missing.goto(base, { waitUntil: 'domcontentloaded' })
    await missing.locator('#portfolio-boot').waitFor({ state: 'detached', timeout: 5000 })
    assert(await missing.locator('html').getAttribute('data-theme') === 'dark', 'Saved dark theme was lost')
    assert(await missing.getByRole('button', { name: 'Open Finder' }).isVisible(), 'Missing wallpaper blocked the portfolio')
    await missingContext.close()

    const failureContext = await browser.newContext({ viewport: { width: 1440, height: 900 } })
    const failure = await failureContext.newPage()
    await failure.route(entry, route => route.abort())
    await failure.goto(base, { waitUntil: 'domcontentloaded' })
    await failure.locator('#portfolio-boot.has-error').waitFor({ state: 'visible', timeout: 5000 })
    assert(await failure.getByRole('button', { name: 'Reload' }).isVisible(), 'Startup recovery action missing')
    await failure.unroute(entry)
    await failure.getByRole('button', { name: 'Reload' }).click()
    await failure.locator('#portfolio-boot').waitFor({ state: 'detached', timeout: 5000 })
    assert(await failure.getByRole('button', { name: 'Open Finder' }).isVisible(), 'Reload did not recover startup')
    await failureContext.close()

    const watchdogContext = await browser.newContext({ viewport: { width: 1440, height: 900 } })
    const watchdogPage = await watchdogContext.newPage()
    await watchdogPage.clock.install()
    await watchdogPage.route(entry, async route => { await pause(2000); await route.abort().catch(() => {}) })
    await watchdogPage.goto(base, { waitUntil: 'commit' })
    await watchdogPage.locator('#portfolio-boot').waitFor({ state: 'visible' })
    await watchdogPage.waitForFunction(() => Boolean(window.portfolioBoot))
    await watchdogPage.clock.fastForward(16000)
    assert(await watchdogPage.locator('#portfolio-boot.has-error').isVisible(), 'Startup watchdog did not offer recovery')
    await watchdogContext.close()

    const phoneContext = await browser.newContext({ viewport: { width: 390, height: 844 }, isMobile: true, deviceScaleFactor: 1 })
    const phone = await phoneContext.newPage()
    await phone.route(entry, async route => { await pause(800); await route.continue() })
    await phone.goto(base, { waitUntil: 'commit' })
    await phone.locator('#portfolio-boot').waitFor({ state: 'visible' })
    await phone.screenshot({ path: path.join(out, 'startup-mobile.png') })
    assert(!(await phone.evaluate(() => document.documentElement.scrollWidth > innerWidth)), 'Mobile startup overflows horizontally')
    await phone.locator('#portfolio-boot').waitFor({ state: 'detached', timeout: 5000 })
    await phone.getByRole('button', { name: 'Open Safari' }).click()
    assert(await phone.locator('.mobile-sheet').isVisible(), 'Mobile navigation blocked after startup')
    await phoneContext.close()

    const reducedContext = await browser.newContext({ viewport: { width: 768, height: 1024 }, reducedMotion: 'reduce' })
    const reduced = await reducedContext.newPage()
    await reduced.route(entry, async route => { await pause(350); await route.continue() })
    const start = Date.now()
    await reduced.goto(base, { waitUntil: 'commit' })
    await reduced.locator('#portfolio-boot').waitFor({ state: 'visible' })
    assert(await reduced.locator('#portfolio-boot').evaluate(el => getComputedStyle(el).transitionDuration) === '0s', 'Reduced motion transition was not disabled')
    await reduced.locator('#portfolio-boot').waitFor({ state: 'detached', timeout: 5000 })
    assert(Date.now() - start < 3000, 'Reduced motion startup took too long')
    assert(await reduced.locator('.desktop-shell').isVisible(), 'Tablet desktop did not appear')
    await reducedContext.close()
    console.log('Startup checks passed: early overlay, progress, cached reload, readiness, theme, asset failure, watchdog, recovery, mobile, tablet, and reduced motion.')
  } finally { await browser.close() }
}
main().catch(error => { console.error(error); process.exitCode = 1 })
